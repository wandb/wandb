// Timing for the spherical cow animation on the logo screen.
const (
	// cowFrame is the delay between animation frames while the cow is on
	// screen.
	cowFrame = 80 * time.Millisecond

	// cowIdlePoll is the delay between checks for the logo screen coming
	// back while the cow is off screen.
	cowIdlePoll = 500 * time.Millisecond

	// cowMaxStep caps a single integration step so the cow doesn't jump
	// after the animation loop idled.
	cowMaxStep = 250 * time.Millisecond
)

// Motion tuning. Horizontal speeds and amplitudes are roughly twice the
// vertical ones because terminal cells are about twice as tall as wide.
const (
	cowHoverGap   = 2   // rows between the logo and the hovering cow
	cowBobAmpY    = 1.0 // rows of vertical bob while hovering
	cowBobAmpX    = 2.0 // cols of horizontal sway while hovering
	cowBobPeriodY = 3.7 // seconds per vertical bob cycle
	cowBobPeriodX = 7.9 // seconds per horizontal sway cycle

	cowRoamSpeedMin = 5.0 // cells/s, horizontal
	cowRoamSpeedMax = 9.0 // cells/s, horizontal
	cowReturnSpeed  = 7.0 // cells/s toward the anchor

	// Extra pane space beyond the sprite size required before the cow is
	// allowed to roam; a bounce needs somewhere to go.
	cowRoamSlackX = 8
	cowRoamSlackY = 4
)

// How long the cow stays in each phase. Randomized per cycle so the
// motion never looks scripted.
const (
	cowHoverDurMin = 8 * time.Second
	cowHoverDurMax = 18 * time.Second
	cowRoamDurMin  = 12 * time.Second
	cowRoamDurMax  = 30 * time.Second
)

// cowSprite parses the cow art once into a cell buffer so frames can be
// blitted with per-cell transparency: blank cells let whatever is behind
// the cow (the logo) show through the bubble.
var cowSprite = sync.OnceValue(func() *lipgloss.Canvas {
	art := strings.Trim(sphericalCowInAVacuum, "\n")
	c := lipgloss.NewCanvas(lipgloss.Width(art), lipgloss.Height(art))
	c.Compose(lipgloss.NewLayer(art))
	return c
})

type cowMode int

const (
	// cowHovering bobs gently at the anchor point below the logo.
	cowHovering cowMode = iota
	// cowRoaming drifts freely, bouncing off the pane edges.
	cowRoaming
	// cowReturning steers back toward the hover anchor.
	cowReturning
)

// SphericalCow animates the spherical-cow-in-an-AI-bubble art on the
// logo screen. Given enough room it hovers below the logo, occasionally
// drifts off to bounce around the pane, and comes back home. In panes
// too short to stack the logo and the cow it roams full-time, floating
// across the logo.
//
// All methods must be called from the Bubble Tea update/view goroutine.
type SphericalCow struct {
	rng *rand.Rand

	mode cowMode

	// x, y is the top-left corner of the sprite in pane cells.
	x, y float64

	// vx, vy is the velocity in cells per second while roaming.
	vx, vy float64

	// anchorX, anchorY is the hover position below the logo.
	anchorX, anchorY float64

	// canHover and canRoam describe what the last rendered pane had room
	// for.
	canHover, canRoam bool

	// paneW, paneH are the dimensions of the last rendered pane.
	paneW, paneH int

	// hoverStart anchors the bob phase; arrival resets it so the sprite
	// lands on the anchor with zero bob offset.
	hoverStart time.Time

	// nextLaunch is when a hovering cow drifts off to roam.
	nextLaunch time.Time

	// returnAt is when a roaming cow starts heading back.
	returnAt time.Time

	// lastTick is the previous integration timestamp.
	lastTick time.Time

	// lastSeen is when the cow was last rendered; the animation loop
	// idles while the logo screen is not on display.
	lastSeen time.Time

	// placed is set once the first Layout gives the cow a position.
	placed bool
}

func NewSphericalCow() *SphericalCow {
	return &SphericalCow{
		rng: rand.New(rand.NewPCG(rand.Uint64(), rand.Uint64())),
	}
}

// cowAnimationCmd schedules the next cow animation frame.
func cowAnimationCmd(delay time.Duration) tea.Cmd {
	return tea.Tick(delay, func(time.Time) tea.Msg {
		return CowAnimationMsg{}
	})
}

// HandleTick advances the animation and schedules the next frame. While
// the logo screen is not being rendered the loop idles at a slow poll.
func (c *SphericalCow) HandleTick(now time.Time) tea.Cmd {
	onScreen := c.placed && now.Sub(c.lastSeen) < 2*cowIdlePoll
	if onScreen {
		c.advance(now)
	}
	c.lastTick = now

	if !onScreen {
		return cowAnimationCmd(cowIdlePoll)
	}
	return cowAnimationCmd(cowFrame)
}

// advance moves the cow along per its current mode.
func (c *SphericalCow) advance(now time.Time) {
	switch c.mode {
	case cowHovering:
		t := now.Sub(c.hoverStart).Seconds()
		c.x = c.anchorX + cowBobAmpX*math.Sin(2*math.Pi*t/cowBobPeriodX)
		c.y = c.anchorY + cowBobAmpY*math.Sin(2*math.Pi*t/cowBobPeriodY)
		if c.canRoam && now.After(c.nextLaunch) {
			c.launch(now)
		}

	case cowRoaming, cowReturning:
		dt := now.Sub(c.lastTick)
		if dt <= 0 {
			return
		}
		dt = min(dt, cowMaxStep)
		if c.mode == cowReturning && c.steerHome(now, dt.Seconds()) {
			return
		}
		c.x += c.vx * dt.Seconds()
		c.y += c.vy * dt.Seconds()
		c.bounce()
		if c.mode == cowRoaming && c.canHover && now.After(c.returnAt) {
			c.mode = cowReturning
		}
	}
}

// launch sends the cow off roaming in a random direction, avoiding
// near-axis-aligned headings (they read as stuck).
func (c *SphericalCow) launch(now time.Time) {
	theta := (0.2 + 0.6*c.rng.Float64()) * math.Pi / 2
	speed := cowRoamSpeedMin +
		(cowRoamSpeedMax-cowRoamSpeedMin)*c.rng.Float64()
	c.vx = speed * math.Cos(theta)
	// Halve the vertical speed to compensate for the cell aspect ratio.
	c.vy = speed * math.Sin(theta) / 2
	if c.rng.IntN(2) == 0 {
		c.vx = -c.vx
	}
	if c.rng.IntN(2) == 0 {
		c.vy = -c.vy
	}
	c.mode = cowRoaming
	c.returnAt = now.Add(randDuration(c.rng, cowRoamDurMin, cowRoamDurMax))
}

// steerHome retargets the velocity at the anchor and reports arrival.
func (c *SphericalCow) steerHome(now time.Time, dt float64) bool {
	dx := c.anchorX - c.x
	dy := c.anchorY - c.y
	// Distance in "square" units: a terminal row is about two cols tall.
	dist := math.Hypot(dx, 2*dy)
	if dist < 1 || dist <= cowReturnSpeed*dt {
		c.arrive(now)
		return true
	}
	c.vx = cowReturnSpeed * dx / dist
	c.vy = cowReturnSpeed * dy / dist
	return false
}

// arrive snaps to the anchor and resumes hovering with zero bob offset.
func (c *SphericalCow) arrive(now time.Time) {
	c.x, c.y = c.anchorX, c.anchorY
	c.mode = cowHovering
	c.hoverStart = now
	c.nextLaunch = now.Add(randDuration(c.rng, cowHoverDurMin, cowHoverDurMax))
}

// bounce reflects the cow off the pane edges.
func (c *SphericalCow) bounce() {
	sprite := cowSprite()
	maxX := float64(max(c.paneW-sprite.Width(), 0))
	maxY := float64(max(c.paneH-sprite.Height(), 0))
	if c.x < 0 {
		c.x = min(-c.x, maxX)
		c.vx = math.Abs(c.vx)
	} else if c.x > maxX {
		c.x = max(2*maxX-c.x, 0)
		c.vx = -math.Abs(c.vx)
	}
	if c.y < 0 {
		c.y = min(-c.y, maxY)
		c.vy = math.Abs(c.vy)
	} else if c.y > maxY {
		c.y = max(2*maxY-c.y, 0)
		c.vy = -math.Abs(c.vy)
	}
}

// clamp keeps the sprite inside the pane without changing direction.
func (c *SphericalCow) clamp() {
	sprite := cowSprite()
	c.x = min(max(c.x, 0), float64(max(c.paneW-sprite.Width(), 0)))
	c.y = min(max(c.y, 0), float64(max(c.paneH-sprite.Height(), 0)))
}

// Layout updates the cow for the pane about to be rendered and returns
// where the logo goes and whether the cow is shown at all.
//
// Panes tall enough to stack the logo, a gap, and the cow center the
// ensemble as a group, with the cow hovering below the logo. Panes that
// only fit the cow with some slack get a full-time roaming cow floating
// across the centered logo. Anything smaller shows the logo only.
func (c *SphericalCow) Layout(
	now time.Time,
	paneW, paneH, logoW, logoH int,
) (logoX, logoY int, showCow bool) {
	sprite := cowSprite()
	cowW, cowH := sprite.Width(), sprite.Height()

	// The +4/+2 margins keep the hover sway (±2 cols) and bob (±1 row)
	// inside the pane.
	c.canHover = paneH >= logoH+cowHoverGap+cowH+2 && paneW >= cowW+4
	c.canRoam = paneW >= cowW+cowRoamSlackX && paneH >= cowH+cowRoamSlackY
	c.paneW, c.paneH = paneW, paneH

	if !c.canHover && !c.canRoam {
		return (paneW - logoW) / 2, (paneH - logoH) / 2, false
	}

	if c.canHover {
		groupH := logoH + cowHoverGap + cowH
		top := (paneH - groupH) / 2
		logoX, logoY = (paneW-logoW)/2, top
		c.anchorX = float64(paneW-cowW) / 2
		c.anchorY = float64(top + logoH + cowHoverGap)
	} else {
		logoX, logoY = (paneW-logoW)/2, (paneH-logoH)/2
		// Nowhere to hover; use the pane center as a nominal anchor.
		c.anchorX = float64(paneW-cowW) / 2
		c.anchorY = float64(paneH-cowH) / 2
	}

	if !c.placed {
		c.x, c.y = c.anchorX, c.anchorY
		c.mode = cowHovering
		c.hoverStart = now
		c.nextLaunch = now.Add(randDuration(c.rng, cowHoverDurMin, cowHoverDurMax))
		c.placed = true
	}

	// The pane may have lost the room the current mode needs.
	switch {
	case !c.canHover && c.mode != cowRoaming:
		c.launch(now)
	case !c.canRoam && c.mode != cowHovering:
		c.arrive(now)
	}
	c.clamp()

	c.lastSeen = now
	return logoX, logoY, true
}

// Blit draws the sprite onto the canvas at the cow's current position.
// Blank cells are skipped so the background shows through the bubble.
func (c *SphericalCow) Blit(canvas *lipgloss.Canvas) {
	sprite := cowSprite()
	px, py := int(math.Round(c.x)), int(math.Round(c.y))
	for cy := range sprite.Height() {
		for cx := range sprite.Width() {
			cell := sprite.CellAt(cx, cy)
			if cell == nil || cell.Content == "" || cell.Content == " " {
				continue
			}
			canvas.SetCell(px+cx, py+cy, cell.Clone())
		}
	}
}

// randDuration returns a uniformly random duration in [lo, hi).
func randDuration(rng *rand.Rand, lo, hi time.Duration) time.Duration {
	return lo + time.Duration(rng.Int64N(int64(hi-lo)))
}

